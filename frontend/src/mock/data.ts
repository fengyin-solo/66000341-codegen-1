export const EVOLUTION_CHAINS: Record<string, EvolutionStage[]> =
  Object.fromEntries(
    Object.entries(RAW_CHAINS).map(([k, stages]) => [
      k,
      stages.map(([word, language, meaning, era, note, gapBefore]) => {
        const s: EvolutionStage = { word, language, meaning, era }
        if (note) s.note = note
        if (gapBefore) s.gapBefore = gapBefore
        return s
      }),
    ])
  )

export function chainKey(root: string, lang: string) { return `${root}|${lang}` }

export function getEvolutionChain(root: string, lang: string): EvolutionStage[] | null {
  return EVOLUTION_CHAINS[chainKey(root, lang)] ?? null
}

export function getNoChainReason(root: string, lang: string): string | null {
  return NO_CHAIN_REASONS[chainKey(root, lang)] ?? null
}
